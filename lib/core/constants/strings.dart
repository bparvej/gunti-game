String tr(String key, [Map<String, String>? args]) {
  final lang = currentLanguage();
  final list = _s[key];
  if (list == null) return key;
  var v = list[lang.index.clamp(0, list.length - 1)];
  args?.forEach((k, val) => v = v.replaceAll('{$k}', val));
  return v;
}

String diffName(Difficulty d) => tr(d.name);

